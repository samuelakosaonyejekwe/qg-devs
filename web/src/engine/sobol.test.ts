import { describe, it, expect } from 'vitest';
import { sobol } from './sobol';

// Reference: scipy.stats.qmc.Sobol(4, scramble=False).random(32)
const REF = [[0, 0, 0, 0], [0.5, 0.5, 0.5, 0.5], [0.75, 0.25, 0.25, 0.25], [0.25, 0.75, 0.75, 0.75], [0.375, 0.375, 0.625, 0.875], [0.875, 0.875, 0.125, 0.375], [0.625, 0.125, 0.875, 0.625], [0.125, 0.625, 0.375, 0.125],
  [0.1875, 0.3125, 0.9375, 0.4375], [0.6875, 0.8125, 0.4375, 0.9375], [0.9375, 0.0625, 0.6875, 0.1875], [0.4375, 0.5625, 0.1875, 0.6875], [0.3125, 0.1875, 0.3125, 0.5625], [0.8125, 0.6875, 0.8125, 0.0625], [0.5625, 0.4375, 0.0625, 0.8125], [0.0625, 0.9375, 0.5625, 0.3125],
  [0.09375, 0.46875, 0.46875, 0.65625], [0.59375, 0.96875, 0.96875, 0.15625], [0.84375, 0.21875, 0.21875, 0.90625], [0.34375, 0.71875, 0.71875, 0.40625], [0.46875, 0.09375, 0.84375, 0.28125], [0.96875, 0.59375, 0.34375, 0.78125], [0.71875, 0.34375, 0.59375, 0.03125], [0.21875, 0.84375, 0.09375, 0.53125],
  [0.15625, 0.15625, 0.53125, 0.84375], [0.65625, 0.65625, 0.03125, 0.34375], [0.90625, 0.40625, 0.78125, 0.59375], [0.40625, 0.90625, 0.28125, 0.09375], [0.28125, 0.28125, 0.15625, 0.21875], [0.78125, 0.78125, 0.65625, 0.71875], [0.53125, 0.03125, 0.40625, 0.46875], [0.03125, 0.53125, 0.90625, 0.96875]];

describe('Sobol sequence', () => {
  it('matches scipy unscrambled Sobol for the first 32 points in 4-D', () => {
    expect(sobol(32, 4)).toEqual(REF);
  });
  it('is balanced: every dyadic interval of width 1/16 holds one of the first 16 points in each dimension', () => {
    const p = sobol(16, 4);
    for (let d = 0; d < 4; d++) {
      const bins = new Set(p.map((x) => Math.floor(x[d] * 16)));
      expect(bins.size).toBe(16);
    }
  });
});
