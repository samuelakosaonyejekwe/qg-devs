export default function Page(_props: { suite?: number }) {
  const sc = useStore(scenario);
  const v = useValidity();
  const models = useImplementedModels();
  const [model, setModel] = useState('QG-COH');
  const [shots, setShots] = useState(5000);
  const [seed, setSeed] = useState(0);
  const [nSteps, setNSteps] = useState(6000);
  const [mcSeed, setMcSeed] = useState(0);
  const sim = useRun(() => apiPost<SimRecord>('/api/signal/simulate', { ...body(sc), model, shots, seed, settings: PAULI_SETTINGS }));
  const rec = sim.data;
  const recDesign = rec ? (rec.generator.config as any)?.design : null;
  return (
    <div>
      <SuiteHeader n={11} intro="Reconstructs physical parameters from measured two-qubit outcome counts. The forward model is a generic coupling family Δφ = λ·Δφ_Newton(design) with free decoherence and local-phase errors. An adaptive Metropolis sampler gives the posterior; Laplace evidences give the Bayes factor for λ free versus λ = 0; the Fisher matrix gives Cramér–Rao bounds and identifiability." />
      <EvidenceBanner />
      <div class="split">
        <div class="sticky-side card">
          <h2>Step 1 · Synthetic data</h2>
          <SelectField label="True (generating) hypothesis" value={model} onChange={setModel} options={models.map((m) => ({ v: m, label: `${m} — ${hypStyle(m).short}` }))}
            help="The hypothesis used to simulate the counts. Inference does not know this: recovering λ ≈ 1 for QG-COH data and λ ≈ 0 for SC-MF/NULL-NG data (in the absence of non-gravitational phases) tests the analysis chain." />
          <div class="form-grid">
            <NumberField name="shots" label="Shots per setting" unit="1" integer value={shots} min={10} max={1e7} report={v.report} onChange={setShots} help="Runs per Pauli setting (all nine settings are simulated). Posterior width shrinks as 1/√N." />
            <NumberField name="seed" label="Simulation seed" unit="1" integer value={seed} min={0} max={2 ** 31 - 1} report={v.report} onChange={setSeed} help="Seed for the synthetic record." />
          </div>
          <ScenarioForm value={sc} onChange={(s) => scenario.set(s)} report={v.report} />
          <RunBar label="Generate counts" scenario busy={sim.busy} disabled={!v.ok} onRun={sim.run} />
        </div>
        <div class="stack">
          <ErrorBox error={sim.error} what="simulating counts" />
          {sim.offline && <p class="small muted">No fresh data was fetched; counts are generated only by the server.</p>}
          {!rec && <InfoBanner>Step 1: generate a synthetic record. Step 2 submits it to the server's inference job.</InfoBanner>}
          {rec && (
            <>
              <SyntheticBanner>Counts generated by <b>{rec.generator.model_id}</b> (seed {rec.generator.seed}); record <code>{shortHash(rec.sha256)}</code>.</SyntheticBanner>
              <Card title="Counts used for inference" actions={<ProvBadge kind="SYNTHETIC" />}>
                <details><summary>Show counts table</summary><CountsTable rec={rec} /></details>
              </Card>
              <Card title="Step 2 · Posterior inference (server job)">
                <div class="form-grid">
                  <NumberField name="nsteps" label="MCMC steps" unit="1" integer value={nSteps} min={3000} max={100000} report={v.report} onChange={setNSteps}
                    help="Length of the adaptive Metropolis chain. The first 2000 steps are discarded as burn-in by the server, so at least 3000 are required here." />
                  <NumberField name="mcseed" label="MCMC seed" unit="1" integer value={mcSeed} min={0} max={2 ** 31 - 1} report={v.report} onChange={setMcSeed} help="Seed of the sampler (reproducibility)." />
                </div>
                <JobRunner scenario type="inference" label="Run inference job" storeKey="inference-s11" disabled={!v.ok}
                  note="Runs in the server's durable job queue (it may wait behind other jobs). The job uses the record's design and readout error."
                  params={() => ({ design: recDesign ?? sc.design, counts: rec.counts, readout_error: sc.environment.readout_error, n_steps: nSteps, seed: mcSeed })}>
                  {(res) => <Result res={res} />}
                </JobRunner>
              </Card>
            </>
          )}
        </div>
      </div>
    </div>
  );
}

function histogram(x: number[], bins = 30): { centers: number[]; counts: number[]; width: number } {
  const lo = Math.min(...x), hi = Math.max(...x);
  const w = (hi - lo) / bins || 1;
  const counts = new Array(bins).fill(0);
  for (const v of x) counts[Math.min(bins - 1, Math.floor((v - lo) / w))]++;
  return { centers: counts.map((_, i) => lo + (i + 0.5) * w), counts, width: w };
}

function Hist({ name, xs, s }: { name: string; xs: number[]; s: any }) {
  const h = useMemo(() => histogram(xs), [xs]);
  const max = Math.max(...h.counts);
  const W = 420, H = 150, pad = 28;
  const lo = h.centers[0] - h.width / 2, hi = h.centers[h.centers.length - 1] + h.width / 2;
  const X = (v: number) => pad + ((v - lo) / (hi - lo)) * (W - 2 * pad);
  return (
    <figure class="chart">
      <figcaption class="chart-title">{name} <span class="small muted">({s?.unit ?? '1'})</span></figcaption>
      <svg viewBox={`0 0 ${W} ${H + 24}`} style={{ width: '100%' }} role="img" aria-label={`Histogram of ${xs.length} posterior samples of ${name}: mean ${fmtNum(s?.mean, 4)}, 95% interval ${fmtNum(s?.ci95?.[0], 3)} to ${fmtNum(s?.ci95?.[1], 3)}`}>
        {s?.ci95 && <rect x={X(s.ci95[0])} y={4} width={Math.max(1, X(s.ci95[1]) - X(s.ci95[0]))} height={H - 4} fill="var(--accent-soft)" />}
        {h.counts.map((c, i) => <rect x={X(h.centers[i] - h.width / 2) + 0.5} y={H - (c / max) * (H - 8)} width={Math.max(1, X(h.centers[i] + h.width / 2) - X(h.centers[i] - h.width / 2) - 1)} height={(c / max) * (H - 8)} fill="var(--accent)" />)}
        {s && <line x1={X(s.mean)} x2={X(s.mean)} y1={2} y2={H} stroke="var(--fg)" stroke-width="1.5" stroke-dasharray="4 3" />}
        {name === 'lambda' && [0, 1].map((ref) => ref >= lo && ref <= hi && <g><line x1={X(ref)} x2={X(ref)} y1={2} y2={H} stroke={ref ? '#0072B2' : '#009E73'} stroke-width="2" /><text x={X(ref) + 3} y={14} font-size="11" fill="currentColor">λ={ref}</text></g>)}
        <line x1={pad} x2={W - pad} y1={H} y2={H} stroke="var(--muted)" />
        <text x={pad} y={H + 16} font-size="11" fill="currentColor">{fmtNum(lo, 3)}</text>
        <text x={W - pad} y={H + 16} font-size="11" fill="currentColor" text-anchor="end">{fmtNum(hi, 3)}</text>
      </svg>
      <div class="small muted">Histogram (computed in the browser) of {xs.length} thinned server MCMC samples; dashed = posterior mean, shaded = 95 % interval.</div>
    </figure>
  );
}

function Result({ res }: { res: any }) {
  const post = res.posterior, bf = res.bayes_factor, fi = res.fisher;
  const names: string[] = post?.names ?? [];
  const samples: number[][] = post?.samples ?? [];
  const lam = post?.summary?.lambda;
  return (
    <div class="stack" style={{ marginTop: '10px' }}>
      <ProvBadge kind="COMPUTED" /> <ProvBadge kind="SYNTHETIC" title="Inferred from synthetic counts" />
      {lam && (
        <div class="outs">
          <Out label="λ posterior mean" value={lam.mean} sig={4} unc={lam.std} prov="COMPUTED"
            interp={`95 % interval [${fmtNum(lam.ci95[0], 3)}, ${fmtNum(lam.ci95[1], 3)}]. ${lam.ci95[0] <= 1 && lam.ci95[1] >= 1 ? 'Consistent with the Newtonian coupling λ = 1.' : 'Excludes λ = 1 at 95 %.'} ${lam.ci95[0] <= 0 && lam.ci95[1] >= 0 ? 'Does not exclude λ = 0.' : 'Excludes λ = 0 at 95 %.'}`} />
          <Out label="ln Bayes factor (λ free vs λ = 0)" value={bf?.ln_B} sig={4} prov="COMPUTED"
            interp={<>Kass–Raftery: <b>{bf?.interpretation}</b>. Method: {bf?.method}; null λ = {String(bf?.null_lambda)}.</>} />
          <Out label="Acceptance rate" value={post.acceptance_rate} sig={3} prov="COMPUTED" interp={`${post.n_samples} post-burn-in samples; 0.15–0.5 indicates healthy mixing.`} />
          {fi && <Out label="Identifiable" value={fi.identifiable ? 'yes' : 'no'} tone={fi.identifiable ? 'good' : 'bad'} prov="COMPUTED" interp={`Fisher condition number ${fmtNum(fi.condition_number, 3)}.`} />}
        </div>
      )}
      <Card title="Posterior summary">
        <DataTable caption="Posterior summary" head={['Parameter', 'Mean', 'Std', 'Median', '95 % interval', 'ESS', 'Cramér–Rao σ', 'Meaning']} numeric={[1, 2, 3, 5, 6]}
          rows={names.map((n) => { const s = post.summary[n]; return [<code>{n}</code>, fmtNum(s.mean, 5), fmtNum(s.std, 3), fmtNum(s.median, 5), `[${fmtNum(s.ci95[0], 4)}, ${fmtNum(s.ci95[1], 4)}]`,
            fmtNum(post.effective_sample_size?.[n], 4), fi?.cramer_rao_std ? fmtNum(fi.cramer_rao_std[n], 3) : '—', <span class="small">{PARAM_INFO[n] ?? ''}</span>]; })} />
        <p class="small muted">Cramér–Rao σ is the Fisher-information lower bound on the standard deviation at the posterior mean for the given shots per setting; a posterior std far above it suggests prior truncation or non-Gaussianity.</p>
      </Card>
      {samples.length > 1 && names.includes('lambda') && names.includes('decay') && names.includes('beta_err') && <ChainView names={names} samples={samples} summary={post.summary} />}
      <div class="grid-2">{names.map((n, k) => <Hist name={n} xs={samples.map((r) => r[k])} s={post.summary[n]} />)}</div>
      {fi && (
        <Card title="Fisher information">
          <BarChart name="fisher-eigenvalues" title="Fisher eigenvalues" desc="Eigenvalues of the expected Fisher information matrix"
            items={fi.eigenvalues.map((e: number, i: number) => ({ label: `μ${i + 1}`, value: e }))} xLabel="Eigenvalue" logX />
          <table class="matrix" aria-label="Fisher information matrix">
            <thead><tr><th />{names.map((n) => <th>{n}</th>)}</tr></thead>
            <tbody>{fi.fisher.map((row: number[], i: number) => <tr><th>{names[i]}</th>{row.map((x) => <td>{fmtNum(x, 3)}</td>)}</tr>)}</tbody>
          </table>
          <p class="small"><StatusBadge status={fi.identifiable ? 'PASSED' : 'FAILED'} /> Identifiability: smallest eigenvalue {fi.identifiable ? 'exceeds' : 'does not exceed'} 10⁻⁹ × largest.</p>
        </Card>
      )}
      <Level min="expert">
        <Card title="Laplace evidence details (expert)">
          <KV rows={[['ln Z (λ free)', fmtNum(bf?.free?.ln_Z, 6)], ['ln Z (λ = 0)', fmtNum(bf?.null?.ln_Z, 6)],
            ['Hessian positive definite', `${bf?.free?.hessian_positive_definite} / ${bf?.null?.hessian_positive_definite}`],
            ['Mode near prior boundary', `${(bf?.free?.mode_near_prior_boundary ?? []).join(', ') || 'none'} / ${(bf?.null?.mode_near_prior_boundary ?? []).join(', ') || 'none'}`]]} />
          <Json data={{ ...res, posterior: { ...post, samples: `[${samples.length} samples omitted]` } }} />
        </Card>
      </Level>
    </div>
  );
}

// ----------------------------------------------------------------------------- animated chain
/**
 * The server's MCMC chain (post burn-in, thinned to ≤ 1000 samples as returned) replayed in chain order:
 * a 3-D scatter of (λ, Γt, β_err) growing sample by sample with the most recent steps highlighted, and
 * synchronised 2-D trace plots.
 */
function ChainView({ names, samples, summary }: { names: string[]; samples: number[][]; summary: Record<string, any> }) {
  const iL = names.indexOf('lambda'), iD = names.indexOf('decay'), iB = names.indexOf('beta_err');
  const n = samples.length;
  const p = usePlayer(n, 60);
  const [view, setView] = useState<'3d' | '2d'>('3d');
  const shown = Math.max(1, Math.min(n, Math.floor(p.pos) + 1));
  const range = (k: number, extra: number[] = []) => {
    const xs = samples.map((r) => r[k]).concat(extra);
    const lo = Math.min(...xs), hi = Math.max(...xs), pad = (hi - lo) * 0.08 || 0.05;
    return [lo - pad, hi + pad] as [number, number];
  };
  const [l0, l1] = range(iL), [d0, d1] = range(iD), [b0, b1] = range(iB);
  const pts = useMemo(() => samples.map((r) => [r[iL], r[iD], r[iB]] as [number, number, number]), [samples]);
  const spec = useMemo(() => {
    const trailStart = Math.max(0, shown - 25);
    const refs: [number, number, number][] = [];
    const notes: { at: [number, number, number]; text: string; color?: string }[] = [];
    for (const [lam, txt, col] of [[1, 'λ = 1 (QG-COH)', '#0072B2'], [0, 'λ = 0 (no coupling)', '#009E73']] as const) {
      if (lam >= l0 && lam <= l1) { refs.push([lam, d0, b0]); notes.push({ at: [lam, d0, b0 + (b1 - b0) * 0.08], text: txt, color: col }); }
    }
    return {
      x: { label: 'λ coupling scale', unit: '1', min: l0, max: l1 }, y: { label: 'decay Γt', unit: '1', min: d0, max: d1 }, z: { label: 'β_err', unit: 'rad', min: b0, max: b1 },
      points: [
        { name: 'chain', pts: pts.slice(0, shown), color: '#56B4E9', size: 0.012 },
        { name: 'recent steps', pts: pts.slice(trailStart, shown), color: '#D55E00', size: 0.018, line: true, lineWidth: 2, highlightLast: true },
        ...(refs.length ? [{ name: 'reference', pts: refs, color: '#009E73', size: 0.03 }] : []),
      ],
      notes,
    };
  }, [shown, pts]);
  const idx = samples.map((_, i) => i);
  const outside = [0, 1].filter((lam) => lam < l0 || lam > l1);
  return (
    <Card title="MCMC chain replay" actions={<ProvBadge kind="COMPUTED" />}>
      <p class="small muted">Replays the server's adaptive-Metropolis chain in sample order ({n} samples after burn-in, thinned by the server as returned — not every step is shown). Points are actual chain samples; nothing is interpolated.{outside.length ? ` λ = ${outside.join(' and ')} lies outside the sampled range and is not drawn.` : ''}</p>
      <Seg label="View" value={view} onChange={setView} options={[{ v: '3d', label: '3-D posterior scatter' }, { v: '2d', label: '2-D traces' }]} />
      {view === '3d' && (
        <View3D kind="plot3d" opts={spec} name="mcmc-chain" title={`Posterior samples 1–${shown} of ${n}`} badge="COMPUTED" playing={p.playing}
          label="Three-dimensional scatter of MCMC samples of coupling scale, decay and local phase error"
          legend={[{ label: 'chain samples', color: '#56B4E9' }, { label: 'last 25 steps', color: '#D55E00' }, { label: 'λ reference (on floor edge)', color: '#009E73' }]}
          onRecordStart={() => { p.setPos(0); p.setPlaying(true); }}
          frameData={() => ({ samples_shown: shown, names: ['lambda', 'decay', 'beta_err'], last: pts[shown - 1], summary })}
          fallback={<Traces idx={idx} samples={samples} iL={iL} iD={iD} iB={iB} pos={p.pos} />} />
      )}
      <PlayerControls p={p} n={n} label="Chain" />
      {view === '2d' && <Traces idx={idx} samples={samples} iL={iL} iD={iD} iB={iB} pos={p.pos} />}
    </Card>
  );
}

function Traces({ idx, samples, iL, iD, iB, pos }: { idx: number[]; samples: number[][]; iL: number; iD: number; iB: number; pos: number }) {
  return (
    <div class="grid-3">
      <LinePlot name="trace-lambda" title="λ trace" desc="Coupling scale versus sample index" xLabel="Sample" yLabel="λ" cursorX={pos} hlines={[{ y: 1, label: 'λ = 1', color: '#0072B2' }]}
        series={[{ name: 'λ', x: idx, y: samples.map((r) => r[iL]), color: '#0072B2', width: 1.2 }]} />
      <LinePlot name="trace-decay" title="Γt trace" desc="Decay exponent versus sample index" xLabel="Sample" yLabel="Γt" cursorX={pos}
        series={[{ name: 'Γt', x: idx, y: samples.map((r) => r[iD]), color: '#E69F00', width: 1.2 }]} />
      <LinePlot name="trace-beta" title="β_err trace" desc="Local phase error on A versus sample index" xLabel="Sample" yLabel="β_err" yUnit="rad" cursorX={pos}
        series={[{ name: 'β_err', x: idx, y: samples.map((r) => r[iB]), color: '#009E73', width: 1.2 }]} />
    </div>
  );
}
